-- Insert order for auth_challenges (ADR 0005, slice 1c.2).
--
-- Rolling back a failed magic-link send restores "the newest" predecessor. On
-- D1 that meant the newest by SQLite rowid, which is insert order; issued_at
-- can tie within a millisecond and challenge ids are random, so neither can
-- stand in for it. issue_seq is that insert order. BY DEFAULT, so the #348
-- importer can carry D1's rowid across and then restart the identity above it.
ALTER TABLE auth_challenges ADD COLUMN issue_seq bigint GENERATED BY DEFAULT AS IDENTITY;
